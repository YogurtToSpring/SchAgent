# ---------- 处理函数 ----------
def to_pinyin(name):
    """将中文名转为全拼小写"""
    pinyins = pinyin(name, style=Style.NORMAL)
    return ''.join([item[0] for item in pinyins])

def process_line(line, index):
    """
    根据行索引 index（从0开始）生成学生记录
    返回: (id, student_id, name, class_id, password, gpa)
    """
    name = line.strip()
    if not name:
        return None

    # 分配班级和学号
    if index < 210:
        # 前210：班级 C003-C008
        cls_num = 3 + index // 35          # 03~08
        seq = index % 35                   # 00~34
        prefix = "202530211"
        pre = "C"
    elif index < 420:
        # 中间210：班级 C001-C006
        local_idx = index - 210
        cls_num = 1 + local_idx // 35      # 01~06
        seq = local_idx % 35
        prefix = "202530212"
        pre = "D"
    elif index < 630:
        # 后210：班级 C001-C006
        local_idx = index - 420
        cls_num = 1 + local_idx // 35
        seq = local_idx % 35
        prefix = "202530213"
        pre = "E"
    elif index < 673:
        # 弘毅班 43人（index 630~672）
        local_idx = index - 630
        cls_num = 2          # 固定班级02（对应C019）
        seq = local_idx      # 00~42
        prefix = "202530211"
    else:
        # 雷军班 30人（index 673~702）
        local_idx = index - 673
        cls_num = 1          # 固定班级01（对应C020）
        seq = local_idx      # 00~29
        prefix = "202530211"

    # 生成学号
    student_id = f"{prefix}{cls_num:02d}{seq:02d}"
    class_id = f"{pre}{cls_num:03d}" if index < 630 else (f"C002" if index < 673 else "C001")

    # 密码：用姓名的拼音，加上取模（比如用 index 取模 13331，或其他）
    # 你原代码用的是 num_val % 13331，这里我们用 index 代替原编号
    pinyin_name = to_pinyin(name)
    password = pinyin_name + f"{int(student_id)* 131 % 13331:04d}"  # 拼音+取模
    # 如果你需要哈希，可以取消下面注释并导入 hash_password
    from teacher import hash_password
    password = hash_password(password)

    # 固定 gpa 为 0.0
    gpa = 0.0

    # id 留空
    return ("", student_id, name, class_id, password, gpa)

# ---------- 执行转换 ----------
lines = raw_data.strip().split('\n')
results = []
for idx, line in enumerate(lines):
    if not line:
        continue
    processed = process_line(line, idx)
    if processed:
        results.append(processed)

# ---------- 输出为CSV ----------
import csv

with open('students_final.csv', 'w', newline='', encoding='utf-8-sig') as f:
    writer = csv.writer(f)
    writer.writerow(['id', 'student_id', 'name', 'class_id', 'password', 'gpa'])
    writer.writerows(results)

print(f"转换完成！共生成 {len(results)} 条记录，已保存到 students_final.csv")
